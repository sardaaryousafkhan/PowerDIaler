const KNOWN_WEAK_AUTH_SECRETS = new Set([
  "local-dev-change-this-auth-secret-1234",
  "replace-with-a-long-random-secret",
]);
const DEFAULT_OWNER_PASSWORD = "OwnerChangeMe123!";
const usesDefaultAuthSecret = KNOWN_WEAK_AUTH_SECRETS.has(parsed.AUTH_SECRET);
const usesDefaultOwnerPassword = parsed.OWNER_PASSWORD === DEFAULT_OWNER_PASSWORD;

if (parsed.NODE_ENV === "production" && (usesDefaultAuthSecret || usesDefaultOwnerPassword)) {
  throw new Error(
    "Refusing to start in production with default secrets. Set AUTH_SECRET and OWNER_PASSWORD in apps/api/.env.",
  );
}
if (!DEMO_MODE && (usesDefaultAuthSecret || usesDefaultOwnerPassword)) {
  console.warn(
    "[security] AUTH_SECRET and/or OWNER_PASSWORD are still the built-in defaults. Change them in apps/api/.env before real use.",
  );
}

